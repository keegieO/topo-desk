function projectOffset(n0, e0, along, offset, azimuthDeg) {
	const az = azimuthDeg * Math.PI / 180;
	const c = Math.cos(az);
	const s = Math.sin(az);
	return {
		n: n0 + along * c - offset * s,
		e: e0 + along * s + offset * c
	};
}
function dist2d(a, b) {
	const an = a.northing ?? a.n ?? 0;
	const ae = a.easting ?? a.e ?? 0;
	const bn = b.northing ?? b.n ?? 0;
	const be = b.easting ?? b.e ?? 0;
	return Math.hypot(an - bn, ae - be);
}
