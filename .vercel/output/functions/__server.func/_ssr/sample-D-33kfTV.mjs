function range(from, to, step) {
	const out = [];
	if (step === 0) return out;
	const dir = from < to ? 1 : -1;
	const s = Math.abs(step);
	for (let a = from; dir > 0 ? a <= to + 1e-6 : a >= to - 1e-6; a += dir * s) out.push(a);
	if (Math.abs(out[out.length - 1] - to) > 1e-6) out.push(to);
	return out;
}
